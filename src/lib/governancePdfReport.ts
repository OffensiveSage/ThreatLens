/**
 * governancePdfReport — generates a multi-page governance PDF using jsPDF.
 *
 * Data source: EXCLUSIVELY structured AgenticReport from runSecurityScan()
 * mapped through complianceMapper. No chat messages or RAG responses used.
 *
 * Pages:
 *   1. Title page
 *   2. Executive Summary
 *   3. NIST CSF Maturity
 *   4. NIS2 Compliance Status
 *   5. NIST 800-53 Violated Controls (with real control text if NIST indexed)
 *   6-7. Detailed Findings (real file:line, code context, specific remediation)
 *   8. Recommendations
 */

import type { ComplianceResult, MappedFinding } from "./complianceMapper";
import type { AgenticReport } from "./agenticScan";

// eslint-disable-next-line @typescript-eslint/no-explicit-any
type jsPDFInstance = any;

const SEV_COLORS: Record<string, [number, number, number]> = {
	CRITICAL: [183, 28, 28],
	HIGH:     [230, 81, 0],
	MEDIUM:   [245, 127, 23],
	LOW:      [46, 125, 50],
};

const STATUS_COLORS: Record<string, [number, number, number]> = {
	"Non-Compliant":     [183, 28, 28],
	"Partial":           [230, 81, 0],
	"Needs Improvement": [245, 127, 23],
	"Pass":              [46, 125, 50],
	"Not Assessed":      [120, 120, 120],
};

function sevRgb(sev: string): [number, number, number] {
	return SEV_COLORS[sev?.toUpperCase()] ?? [90, 90, 90];
}

function addFooter(doc: jsPDFInstance, page: number, total: number, date: string) {
	const w = doc.internal.pageSize.getWidth();
	const h = doc.internal.pageSize.getHeight();
	doc.setFontSize(7);
	doc.setFont("helvetica", "normal");
	doc.setTextColor(150, 150, 150);
	doc.text(`Generated by ThreatLens · Agentic Scan Pipeline · Confidential · ${date}`, 14, h - 9);
	doc.text(`Page ${page} of ${total}`, w - 14, h - 9, { align: "right" });
	// Thin rule above footer
	doc.setDrawColor(210, 210, 210);
	doc.line(14, h - 13, w - 14, h - 13);
}

function sectionHeader(doc: jsPDFInstance, text: string, y: number): number {
	const w = doc.internal.pageSize.getWidth();
	doc.setFillColor(30, 30, 30);
	doc.rect(14, y, w - 28, 9, "F");
	doc.setFontSize(8);
	doc.setFont("helvetica", "bold");
	doc.setTextColor(245, 166, 35);
	doc.text(text.toUpperCase(), 18, y + 6);
	return y + 13;
}

function wrap(doc: jsPDFInstance, text: string, x: number, y: number, maxW: number, lh = 5): number {
	const lines = doc.splitTextToSize(String(text), maxW) as string[];
	doc.text(lines, x, y);
	return y + lines.length * lh;
}

function checkNewPage(doc: jsPDFInstance, y: number, needed = 30): number {
	if (y + needed > doc.internal.pageSize.getHeight() - 20) {
		doc.addPage();
		return 20;
	}
	return y;
}

/** Build a GitHub permalink for a file:line in the scanned repo. */
function ghLink(owner: string, repo: string, file: string, line?: number): string {
	return `https://github.com/${owner}/${repo}/blob/main/${file}${line ? `#L${line}` : ""}`;
}

// ─── Main export ──────────────────────────────────────────────────────────────

export async function generateGovernancePDF(
	owner: string,
	repo: string,
	report: AgenticReport,
	compliance: ComplianceResult,
	/** Control description text loaded from NIST IndexedDB (empty map if not indexed) */
	nistDescriptions: Record<string, string> = {},
	nistIndexed = false
): Promise<void> {
	const { jsPDF } = await import("jspdf");
	// eslint-disable-next-line @typescript-eslint/no-explicit-any
	const autoTable = (await import("jspdf-autotable")).default as any;

	const doc = new jsPDF({ orientation: "portrait", unit: "mm", format: "a4" });
	const W = doc.internal.pageSize.getWidth();
	const dateStr = new Date().toLocaleDateString("en-US", { year: "numeric", month: "long", day: "numeric" });
	const shortDate = new Date().toISOString().slice(0, 10);
	const scannedAt = report.scannedAt instanceof Date ? report.scannedAt.toLocaleString() : String(report.scannedAt);

	// ── PAGE 1: TITLE ─────────────────────────────────────────────────────────
	doc.setFillColor(15, 15, 15);
	doc.rect(0, 0, W, 297, "F");

	doc.setFontSize(32);
	doc.setFont("helvetica", "bold");
	doc.setTextColor(245, 166, 35);
	doc.text("THREATLENS", W / 2, 56, { align: "center" });

	doc.setFontSize(13);
	doc.setFont("helvetica", "normal");
	doc.setTextColor(200, 200, 200);
	doc.text("Security Posture & Compliance Report", W / 2, 68, { align: "center" });

	doc.setFontSize(11);
	doc.setTextColor(140, 140, 140);
	doc.text(`${owner}/${repo}`, W / 2, 80, { align: "center" });
	doc.text(dateStr, W / 2, 87, { align: "center" });

	// Source attribution box
	doc.setFillColor(30, 30, 30);
	doc.roundedRect(W / 2 - 60, 95, 120, 12, 2, 2, "F");
	doc.setFontSize(7);
	doc.setTextColor(100, 180, 100);
	doc.text("Source: Agentic Scan Pipeline (runSecurityScan) · No chat messages used", W / 2, 103, { align: "center" });

	// Risk score
	const score = compliance.riskScore;
	const scoreRgb: [number, number, number] = score >= 75 ? [46, 125, 50] : score >= 50 ? [245, 127, 23] : [183, 28, 28];
	doc.setFillColor(...scoreRgb);
	doc.roundedRect(W / 2 - 22, 116, 44, 40, 3, 3, "F");
	doc.setFontSize(26);
	doc.setFont("helvetica", "bold");
	doc.setTextColor(255, 255, 255);
	doc.text(String(score), W / 2, 135, { align: "center" });
	doc.setFontSize(7);
	doc.setFont("helvetica", "normal");
	doc.text("RISK SCORE / 100", W / 2, 143, { align: "center" });
	doc.text("(higher = more secure)", W / 2, 149, { align: "center" });

	doc.setFontSize(7);
	doc.setTextColor(80, 80, 80);
	doc.text("CONFIDENTIAL — FOR INTERNAL GOVERNANCE USE ONLY", W / 2, 270, { align: "center" });

	// ── PAGE 2: EXECUTIVE SUMMARY ─────────────────────────────────────────────
	doc.addPage();
	let y = 18;

	doc.setFontSize(16);
	doc.setFont("helvetica", "bold");
	doc.setTextColor(245, 166, 35);
	doc.text("Executive Summary", 14, y);
	y += 8;

	doc.setFontSize(8);
	doc.setFont("helvetica", "normal");
	doc.setTextColor(80, 80, 80);
	doc.text(`Repository: ${owner}/${repo}   |   Scanned: ${scannedAt}   |   Files: ${report.summary.filesScanned}   |   Languages: ${report.summary.languages.join(", ")}`, 14, y);
	y += 8;

	// 5 stat boxes
	const counts = report.summary.counts;
	const numericCSF = Object.values(compliance.nistCSF.scores).filter((s): s is number => typeof s === "number");
	const avgCSF = numericCSF.length > 0 ? Math.round(numericCSF.reduce((a, b) => a + b, 0) / numericCSF.length) : 0;

	const stats = [
		{ label: "Risk Score", value: `${score}/100` },
		{ label: "Findings",   value: String(report.summary.totalFindings) },
		{ label: "CSF Score",  value: `${avgCSF}%` },
		{ label: "NIS2 Ready", value: `${compliance.nis2.readinessPercent}%` },
		{ label: "Controls",   value: String(compliance.nist80053.totalViolatedControls) },
	];
	const cardW = (W - 28 - 4 * 3) / 5;
	for (let i = 0; i < stats.length; i++) {
		const cx = 14 + i * (cardW + 3);
		doc.setFillColor(240, 240, 240);
		doc.rect(cx, y, cardW, 20, "F");
		doc.setFontSize(14);
		doc.setFont("helvetica", "bold");
		doc.setTextColor(245, 166, 35);
		doc.text(stats[i].value, cx + cardW / 2, y + 11, { align: "center" });
		doc.setFontSize(6);
		doc.setFont("helvetica", "normal");
		doc.setTextColor(80, 80, 80);
		doc.text(stats[i].label, cx + cardW / 2, y + 17, { align: "center" });
	}
	y += 26;

	// Severity breakdown
	y = sectionHeader(doc, "Findings by Severity", y);
	const sevOrder = ["CRITICAL", "HIGH", "MEDIUM", "LOW"] as const;
	const maxSevCnt = Math.max(...sevOrder.map((s) => counts[s] ?? 0), 1);
	for (const sev of sevOrder) {
		const cnt = counts[sev] ?? 0;
		const barW = ((cnt / maxSevCnt) * (W - 80));
		doc.setFillColor(...sevRgb(sev));
		doc.rect(40, y, Math.max(barW, 1), 4, "F");
		doc.setFontSize(7);
		doc.setFont("helvetica", "bold");
		doc.setTextColor(...sevRgb(sev));
		doc.text(sev, 14, y + 3.5);
		doc.setFont("helvetica", "normal");
		doc.setTextColor(60, 60, 60);
		doc.text(String(cnt), W - 14, y + 3.5, { align: "right" });
		y += 9;
	}
	y += 4;

	// Key insight paragraph
	y = sectionHeader(doc, "Key Insight", y);
	doc.setFontSize(8);
	doc.setFont("helvetica", "normal");
	doc.setTextColor(50, 50, 50);

	const critCnt = counts["CRITICAL"] ?? 0;
	const highCnt = counts["HIGH"] ?? 0;
	const worstFamily = Object.entries(compliance.nist80053.families).sort((a, b) => b[1].total_violated - a[1].total_violated)[0];

	const insights = [
		`${report.summary.totalFindings} confirmed finding${report.summary.totalFindings !== 1 ? "s" : ""} across ${report.summary.filesScanned} files: ${critCnt} CRITICAL, ${highCnt} HIGH severity.`,
		worstFamily
			? `Most impacted NIST 800-53 family: ${worstFamily[0]} with ${worstFamily[1].total_violated} violated controls (max severity: ${worstFamily[1].max_severity}).`
			: "No NIST 800-53 controls were violated based on the code scan.",
		`NIS2 readiness from code analysis: ${compliance.nis2.readinessPercent}% (${compliance.nis2.assessedFromCode} of ${compliance.nis2.totalArticles} articles code-assessable; ${compliance.nis2.notAssessed} require policy review).`,
		nistIndexed
			? "NIST 800-53 control descriptions sourced from indexed data."
			: "Index NIST 800-53 in ThreatLens for full control requirement descriptions.",
	];
	for (const line of insights) {
		y = wrap(doc, line, 14, y, W - 28, 5);
		y += 2;
	}

	// ── PAGE 3: NIST CSF MATURITY ─────────────────────────────────────────────
	doc.addPage();
	y = 18;
	doc.setFontSize(16);
	doc.setFont("helvetica", "bold");
	doc.setTextColor(245, 166, 35);
	doc.text("NIST CSF Maturity", 14, y);
	y += 12;

	const csfFunctions = ["Identify", "Protect", "Detect", "Respond", "Recover"];
	const csfFnColors: Record<string, [number, number, number]> = {
		Identify: [100, 181, 246],
		Protect:  [245, 166, 35],
		Detect:   [102, 187, 106],
		Respond:  [255, 138, 101],
		Recover:  [206, 147, 216],
	};

	autoTable(doc, {
		startY: y,
		head: [["Function", "Score", "Code-Assessable", "Category Breakdown"]],
		body: csfFunctions.map((fn) => {
			const s = compliance.nistCSF.scores[fn];
			const scoreStr = s === "N/A" ? "N/A — Policy review required" : `${s}%`;
			const assessable = compliance.nistCSF.assessableFromCode[fn] ? "Yes" : "No";
			const prefix = fn.slice(0, 2).toUpperCase();
			const cats = Object.entries(compliance.nistCSF.categoryFindings)
				.filter(([cat]) => cat.startsWith(prefix))
				.map(([cat, fns]) => `${cat}: ${(fns as unknown[]).length}`)
				.join(", ") || "No findings";
			return [fn, scoreStr, assessable, cats];
		}),
		styles: { fontSize: 8, cellPadding: 3 },
		headStyles: { fillColor: [26, 26, 26], textColor: [245, 166, 35], fontStyle: "bold" },
		didParseCell: (data: { row: { index: number }; column: { index: number }; cell: { styles: { textColor: [number, number, number] } } }) => {
			if (data.column.index === 0 && data.row.index >= 0) {
				data.cell.styles.textColor = csfFnColors[csfFunctions[data.row.index]] ?? [60, 60, 60];
			}
		},
	});

	y = (doc as unknown as { lastAutoTable: { finalY: number } }).lastAutoTable.finalY + 10;
	y = sectionHeader(doc, "Note on Scope", y);
	doc.setFontSize(8);
	doc.setFont("helvetica", "normal");
	doc.setTextColor(80, 80, 80);
	wrap(doc, "Identify, Respond, and Recover functions require policy documentation, incident response plans, and BCP reviews that cannot be assessed from code alone. Scores shown are code-analysis only.", 14, y, W - 28);

	// ── PAGE 4: NIS2 COMPLIANCE ───────────────────────────────────────────────
	doc.addPage();
	y = 18;
	doc.setFontSize(16);
	doc.setFont("helvetica", "bold");
	doc.setTextColor(245, 166, 35);
	doc.text("NIS2 Compliance Status", 14, y);
	y += 10;

	doc.setFontSize(8);
	doc.setFont("helvetica", "normal");
	doc.setTextColor(60, 60, 60);
	doc.text(`Overall Readiness (code-assessable articles only): ${compliance.nis2.readinessPercent}%`, 14, y);
	y += 5;
	doc.setFillColor(210, 210, 210);
	doc.rect(14, y, W - 28, 4, "F");
	doc.setFillColor(46, 125, 50);
	doc.rect(14, y, ((W - 28) * compliance.nis2.readinessPercent) / 100, 4, "F");
	y += 10;

	const nis2Rows = Object.values(compliance.nis2.articles).map((art) => [
		art.article,
		art.title,
		art.status,
		art.finding_count > 0 ? String(art.finding_count) : "—",
		art.findings.slice(0, 2).map((f) => `${f.name} (${f.severity})`).join("; ") || art.statusNote || "—",
	]);

	autoTable(doc, {
		startY: y,
		head: [["Article", "Title", "Status", "#", "Key Issues"]],
		body: nis2Rows,
		styles: { fontSize: 7, cellPadding: 2 },
		headStyles: { fillColor: [26, 26, 26], textColor: [245, 166, 35], fontStyle: "bold" },
		columnStyles: { 0: { cellWidth: 26 }, 1: { cellWidth: 48 }, 2: { cellWidth: 26 }, 3: { cellWidth: 8 } },
		didParseCell: (data: { column: { index: number }; row: { index: number }; cell: { styles: { textColor: [number, number, number]; fontStyle: string } } }) => {
			if (data.column.index === 2 && data.row.index >= 0) {
				data.cell.styles.textColor = STATUS_COLORS[nis2Rows[data.row.index]?.[2]] ?? [60, 60, 60];
				data.cell.styles.fontStyle = "bold";
			}
		},
	});

	// ── PAGE 5: NIST 800-53 VIOLATED CONTROLS ────────────────────────────────
	doc.addPage();
	y = 18;
	doc.setFontSize(16);
	doc.setFont("helvetica", "bold");
	doc.setTextColor(245, 166, 35);
	doc.text("NIST 800-53 Violated Controls", 14, y);
	y += 12;

	if (!nistIndexed) {
		doc.setFontSize(8);
		doc.setFont("helvetica", "italic");
		doc.setTextColor(100, 181, 246);
		y = wrap(doc, "Tip: Index NIST 800-53 in ThreatLens to display full control requirement text alongside each violation.", 14, y, W - 28);
		y += 4;
	}

	// Build rows with control description if available
	for (const [family, familyData] of Object.entries(compliance.nist80053.families).sort((a, b) => b[1].total_violated - a[1].total_violated)) {
		y = checkNewPage(doc, y, 20);

		// Family header
		doc.setFillColor(40, 40, 40);
		doc.rect(14, y, W - 28, 7, "F");
		doc.setFontSize(8);
		doc.setFont("helvetica", "bold");
		doc.setTextColor(245, 166, 35);
		doc.text(`${family} Family — ${familyData.total_violated} controls violated — Max: ${familyData.max_severity}`, 18, y + 5);
		y += 10;

		for (const ctrl of familyData.controls) {
			y = checkNewPage(doc, y, 30);

			// Control ID row
			doc.setFillColor(50, 50, 50);
			doc.rect(14, y, W - 28, 6, "F");
			doc.setFontSize(8);
			doc.setFont("helvetica", "bold");
			doc.setTextColor(220, 220, 220);
			doc.text(ctrl.controlId, 18, y + 4.5);
			doc.setFont("helvetica", "normal");
			doc.setTextColor(...sevRgb(familyData.max_severity));
			doc.text(familyData.max_severity, W - 14, y + 4.5, { align: "right" });
			y += 8;

			// Control requirement text
			const desc = nistDescriptions[ctrl.controlId];
			if (desc) {
				doc.setFontSize(7);
				doc.setFont("helvetica", "italic");
				doc.setTextColor(120, 180, 120);
				doc.text("Control Requirement:", 18, y);
				y += 4;
				doc.setFont("helvetica", "normal");
				doc.setTextColor(60, 60, 60);
				y = wrap(doc, desc, 18, y, W - 36, 4.5);
				y += 2;
			}

			// Findings under this control
			for (const f of ctrl.findings) {
				y = checkNewPage(doc, y, 22);

				// Violation
				doc.setFontSize(7);
				doc.setFont("helvetica", "bold");
				doc.setTextColor(...sevRgb(f.severity));
				doc.text(`Violation [${f.severity}]:`, 22, y);
				doc.setFont("helvetica", "normal");
				doc.setTextColor(40, 40, 40);
				y = wrap(doc, `${f.finding}${f.cwe ? `  (${f.cwe})` : ""}`, 22, y + 4.5, W - 40, 4.5);
				y += 1;

				// Evidence with GitHub link
				if (f.file) {
					const fileRef = `${f.file}${f.line ? `:${f.line}` : ""}`;
					const url = ghLink(owner, repo, f.file, f.line);
					doc.setFontSize(7);
					doc.setFont("helvetica", "bold");
					doc.setTextColor(80, 80, 80);
					doc.text("Evidence:", 22, y);
					doc.setFont("helvetica", "normal");
					doc.setTextColor(245, 166, 35);
					doc.textWithLink(fileRef, 40, y, { url });
					y += 6;
				}
			}
			y += 4;
		}
	}

	// ── PAGES 6-7: DETAILED FINDINGS ─────────────────────────────────────────
	doc.addPage();
	y = 18;
	doc.setFontSize(16);
	doc.setFont("helvetica", "bold");
	doc.setTextColor(245, 166, 35);
	doc.text("Detailed Findings", 14, y);
	y += 10;
	doc.setFontSize(7);
	doc.setFont("helvetica", "normal");
	doc.setTextColor(100, 100, 100);
	doc.text("All data sourced directly from the agentic scan pipeline. Severity confirmed by LLM deep analysis where available.", 14, y);
	y += 10;

	const sortedFindings: MappedFinding[] = [...compliance.mappedFindings].sort((a, b) => {
		const r: Record<string, number> = { CRITICAL: 4, HIGH: 3, MEDIUM: 2, LOW: 1 };
		return (r[b.severity] ?? 0) - (r[a.severity] ?? 0);
	});

	for (const f of sortedFindings) {
		y = checkNewPage(doc, y, 45);

		// Finding header bar
		doc.setFillColor(...sevRgb(f.severity));
		doc.rect(14, y, 4, 22, "F");
		doc.setFillColor(42, 42, 42);
		doc.rect(18, y, W - 32, 22, "F");

		doc.setFontSize(8);
		doc.setFont("helvetica", "bold");
		doc.setTextColor(...sevRgb(f.severity));
		doc.text(f.severity, 22, y + 6);
		doc.setTextColor(220, 220, 220);
		doc.text(f.name, 22 + 24, y + 6);

		doc.setFontSize(7);
		doc.setFont("helvetica", "normal");
		doc.setTextColor(160, 160, 160);
		if (f.cwe) doc.text(`CWE: ${f.cwe}`, 22, y + 12);
		if (f.file) {
			const fileRef = `${f.file}${f.line ? `:${f.line}` : ""}`;
			const url = ghLink(owner, repo, f.file, f.line);
			doc.setTextColor(245, 166, 35);
			doc.textWithLink(fileRef, 22 + (f.cwe ? 42 : 0), y + 12, { url });
		}

		// NIST / NIS2 tags
		const nistTags = f.compliance.nist_800_53.slice(0, 4).join("  ");
		const nis2Tags = f.compliance.nis2_articles[0]?.split(" - ")[0] ?? "";
		doc.setTextColor(100, 160, 220);
		doc.text(nistTags, 22, y + 18);
		doc.setTextColor(180, 130, 210);
		doc.text(nis2Tags, W - 80, y + 18);

		y += 26;

		// Code context
		if (f.context) {
			y = checkNewPage(doc, y, 16);
			doc.setFontSize(6.5);
			doc.setFont("courier", "normal");
			doc.setTextColor(100, 200, 100);
			doc.setFillColor(25, 35, 25);
			const ctxLines = doc.splitTextToSize(f.context.slice(0, 300), W - 40) as string[];
			const ctxH = ctxLines.length * 4 + 4;
			doc.rect(22, y - 2, W - 36, ctxH, "F");
			doc.text(ctxLines, 24, y + 1.5);
			y += ctxH + 2;
		}

		// Explanation
		if (f.explanation) {
			y = checkNewPage(doc, y, 12);
			doc.setFontSize(7);
			doc.setFont("helvetica", "bold");
			doc.setTextColor(80, 80, 80);
			doc.text("Explanation:", 22, y);
			y += 4;
			doc.setFont("helvetica", "normal");
			doc.setTextColor(50, 50, 50);
			y = wrap(doc, f.explanation, 22, y, W - 40, 4.5);
			y += 2;
		}

		// Remediation (specific to this finding, from LLM)
		if (f.remediation) {
			y = checkNewPage(doc, y, 12);
			doc.setFontSize(7);
			doc.setFont("helvetica", "bold");
			doc.setTextColor(46, 125, 50);
			doc.text("Remediation:", 22, y);
			y += 4;
			doc.setFont("helvetica", "normal");
			doc.setTextColor(50, 70, 50);
			y = wrap(doc, f.remediation, 22, y, W - 40, 4.5);
			y += 2;
		}

		// References (visible text URLs for print)
		const refs: { label: string; url: string }[] = [];
		if (f.file) refs.push({ label: "GitHub", url: ghLink(owner, repo, f.file, f.line) });
		if (f.cwe) {
			const cweNum = f.cwe.replace(/^CWE-/i, "");
			refs.push({ label: `MITRE ${f.cwe}`, url: `https://cwe.mitre.org/data/definitions/${cweNum}.html` });
		}
		for (const ctrl of f.compliance.nist_800_53.slice(0, 2)) {
			refs.push({ label: `NIST ${ctrl}`, url: `https://csf.tools/reference/nist-sp-800-53/r5/${ctrl.toLowerCase()}/` });
		}
		if (refs.length > 0) {
			y = checkNewPage(doc, y, 10);
			doc.setFontSize(6.5);
			doc.setFont("helvetica", "bold");
			doc.setTextColor(100, 100, 100);
			doc.text("References:", 22, y);
			y += 4;
			for (const ref of refs) {
				y = checkNewPage(doc, y, 6);
				doc.setFont("helvetica", "bold");
				doc.setTextColor(120, 120, 120);
				doc.text(`${ref.label}:`, 24, y);
				doc.setFont("helvetica", "normal");
				doc.setTextColor(100, 160, 220);
				doc.textWithLink(ref.url, 24 + doc.getTextWidth(`${ref.label}:`) + 2, y, { url: ref.url });
				y += 4;
			}
			y += 1;
		}

		// Divider
		doc.setDrawColor(55, 55, 55);
		doc.line(14, y, W - 14, y);
		y += 6;
	}

	// ── PAGE 8: RECOMMENDATIONS ──────────────────────────────────────────────
	doc.addPage();
	y = 18;
	doc.setFontSize(16);
	doc.setFont("helvetica", "bold");
	doc.setTextColor(245, 166, 35);
	doc.text("Prioritized Recommendations", 14, y);
	y += 12;

	for (const rec of compliance.recommendations) {
		y = checkNewPage(doc, y, 36);
		const impRgb: [number, number, number] = rec.impact === "High" ? [183, 28, 28] : rec.impact === "Medium" ? [245, 127, 23] : [46, 125, 50];

		// Priority badge
		doc.setFillColor(...impRgb);
		doc.roundedRect(14, y, 9, 9, 1, 1, "F");
		doc.setFontSize(7);
		doc.setFont("helvetica", "bold");
		doc.setTextColor(255, 255, 255);
		doc.text(String(rec.priority), 18.5, y + 6, { align: "center" });

		// Title
		doc.setFontSize(9);
		doc.setFont("helvetica", "bold");
		doc.setTextColor(30, 30, 30);
		doc.text(rec.category.toUpperCase(), 28, y + 6);
		doc.setFontSize(7);
		doc.setFont("helvetica", "normal");
		doc.setTextColor(...impRgb);
		doc.text(`${rec.impact} impact  ·  ${rec.findingCount} finding${rec.findingCount !== 1 ? "s" : ""}  ·  Controls: ${rec.affectedControls.join(", ")}`, 28, y + 11);
		y += 15;

		doc.setFontSize(8);
		doc.setFont("helvetica", "normal");
		doc.setTextColor(50, 50, 50);
		y = wrap(doc, rec.action, 28, y, W - 42, 5);
		y += 6;

		doc.setDrawColor(200, 200, 200);
		doc.line(14, y - 2, W - 14, y - 2);
	}

	// ── FOOTERS ───────────────────────────────────────────────────────────────
	const totalPages = doc.getNumberOfPages();
	for (let p = 1; p <= totalPages; p++) {
		doc.setPage(p);
		addFooter(doc, p, totalPages, shortDate);
	}

	doc.save(`ThreatLens-Governance-${owner}-${repo}-${shortDate}.pdf`);
}
